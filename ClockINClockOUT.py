    #create account (DiscordUserID, FullName, Title) -> void: creates an account with CiCoAccount
    def create_account(DiscordUserID, FullName, Title):
        """
        creates a CiCoAccount standard account and saved it to CiCoUserData.csv

        Parameters:
             DiscordUserID (str | int): users discord id, pre generated by Discord
             FullName (str): Users full name, must align with what is on the generated timesheet by ICode
             Title (str) : Users job title, must align with what is on the generated timesheet by ICode

        :return: returns a string only if the user account is already saved to CiCoUserData.csv
        """
        UserData = pd.read_csv('CiCoUserData.csv', dtype={'col1':str, 'col2':str, 'col3':str})
        file_path = f"{DiscordUserID}.csv"
        DiscordUserID = str(DiscordUserID)
        if UserData.loc[UserData["UserID"] == DiscordUserID].empty:
            newRow = {"UserID": DiscordUserID,
                      "Name": FullName,
                      "Title": Title
                     }
            UserData.loc[len(UserData)] = newRow
            UserData.to_csv("CiCoUserData.csv", index=False)
        
        try:
            with open(file_path, 'x') as file:
                file.write("Date,Clock In,Clock Out,Total Hours\n")
        except FileExistsError:
            print(f"The file {file_path} already exists")

        else:
            return "account is already saved. use /view account to viw account details or /edit to edit any details about your account"




    # get account (DiscordUserID) -> dictionary: searches saved csv for account and creates a dictionary object
    def get_account(self, DiscordUserID):

        """
        Retrieves and returns a user's saved CiCo account.

        searches the 'CiCoUserData.csv' file for a row matching the
        provided DiscordUserID. If the account exists, it is converted into a
        dictionary containing the user's ID, name, and title. A status code of 0 is
        returned alongside the dictionary to indicate success.

        If the account is not found, the function returns an error message and a
        status code of 1

        Parameters:
            DiscordUserID (str | int): The Discord user ID used to locate the account.

        Returns:
            tuple:
                (dict, int) -> On success: a dictionary with account details and status code 0.
                (str, int)  -> On failure: an error message and status code 1.
        """
        UserData = pd.read_csv('CiCoUserData.csv', dtype={'UserID':str, 'Name':str, 'Title':str})
        DiscordUserID = str(DiscordUserID)
        UserAccount = UserData.loc[UserData["UserID"] == DiscordUserID]
        if not UserData.loc[UserData["UserID"] == DiscordUserID].empty:
            UserAccount = { "UserID":UserAccount["UserID"].values[0],
                            "Name": UserAccount["Name"].values[0],
                            "Title": UserAccount["Title"].values[0]
                          }
            return UserAccount, 0
        else:
            return "your account is not saved or im having issues accessing a file. use /create account to make an account", 1


