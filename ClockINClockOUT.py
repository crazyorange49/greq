    #edit (FullName=None, Title=None) -> Void:
    def edit_account(self, FullName=None, Title=None):

        """
        Updates the current user's account information.

        Uses the data stored in self.UserAccount to locate the user's row in
        'CiCoUserData.csv'. If found, updates the Name and/or Title fields with any
        provided values, writes the changes back to the CSV, and updates the local
        account cache.

        Parameters:
            FullName (str, optional): New full name to save.
            Title (str, optional): New job title to save.

        Returns:
            str: Success message, or an error message if the account cannot be found.
        """

        # self.UserAccount = (dict, status_code)
        account_data, status_code = self.UserAccount

        if status_code != 0:
            return "No account found. Please create an account first."

        # Load CSV
        UserData = pd.read_csv('CiCoUserData.csv', dtype={'UserID': str, 'Name': str, 'Title': str})

        # Locate the index of the user's row
        user_index = UserData.index[UserData["UserID"] == account_data["UserID"]].tolist()
        if not user_index:
            return "Error: User account not found in file."

        idx = user_index[0]

        # Update fields if new values are provided
        if FullName is not None:
            UserData.at[idx, "Name"] = FullName
            account_data["Name"] = FullName
        if Title is not None:
            UserData.at[idx, "Title"] = Title
            account_data["Title"] = Title

        # Save updated data back to CSV
        UserData.to_csv("CiCoUserData.csv", index=False)

        # Update self.UserAccount with the new data
        self.UserAccount = (account_data, 0)

        return f"Account for {account_data['UserID']} updated successfully."



